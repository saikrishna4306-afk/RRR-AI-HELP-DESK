"""Offline/real evaluation.  python -m eval.run --mode mock|real   -> writes docs/EVAL.md"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
import statistics
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def pct(values: list[float], p: float) -> float:
    if not values:
        return 0.0
    v = sorted(values)
    return v[min(len(v) - 1, int(round(p / 100 * (len(v) - 1))))]


async def main(mode: str) -> None:
    if mode == "mock":
        tmp = Path(tempfile.mkdtemp())
        os.environ.update({"LLM_PROVIDER": "mock", "LLM_FALLBACK": "mock", "STT_PROVIDER": "mock", "TTS_PROVIDER": "mock",
                           "TTS_FALLBACK": "mock", "VISION_PROVIDER": "mock", "EMBED_PROVIDER": "hash",
                           "DATABASE_URL": f"sqlite:///{(tmp / 'eval.db').as_posix()}"})
    from backend.db import init_db
    from backend.pipeline import HelpDesk

    init_db()
    desk = HelpDesk()
    await desk.startup()
    rows = [json.loads(line) for line in (ROOT / "eval" / "golden.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
    results = []
    for r in rows:
        desk.answer_cache.clear()
        t0 = time.perf_counter()
        out = await desk.ask(text=r["text"], language=r["language"], session_id=f"eval-{r['id']}")
        ms = (time.perf_counter() - t0) * 1000
        pred = "unknown" if out["handoff"] else out["fault_id"]
        results.append({**r, "pred": pred, "conf": out["confidence"], "ms": ms, "handoff": out["handoff"],
                        "providers": ", ".join(f"{u['service']}={u['provider']}" for u in out["providers_used"])})
    answerable = [x for x in results if x["expected"] != "unknown"]
    hit1 = sum(x["pred"] == x["expected"] for x in answerable) / max(1, len(answerable))
    tp = sum(x["handoff"] and x["expected"] == "unknown" for x in results)
    fp = sum(x["handoff"] and x["expected"] != "unknown" for x in results)
    fn = sum((not x["handoff"]) and x["expected"] == "unknown" for x in results)
    prec = tp / max(1, tp + fp)
    rec = tp / max(1, tp + fn)
    lat = [x["ms"] for x in results]
    lines = [
        f"# Evaluation ({mode} mode)",
        "",
        f"Cases: {len(results)} ({len(answerable)} answerable, {len(results) - len(answerable)} unanswerable). "
        f"Generated by `python -m eval.run --mode {mode}`. Note: the golden set was written by the same author as the guides; "
        "treat 100% as a sanity check, not a benchmark. Add real customer phrasings to make it honest.",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| hit@1 (answerable) | {hit1:.2%} |",
        f"| handoff precision | {prec:.2%} |",
        f"| handoff recall | {rec:.2%} |",
        f"| latency p50 | {statistics.median(lat):.0f} ms |",
        f"| latency p95 | {pct(lat, 95):.0f} ms |",
        "",
        "| id | lang | expected | predicted | confidence | ms |",
        "|---|---|---|---|---|---|",
    ] + [f"| {x['id']} | {x['language']} | {x['expected']} | {x['pred']} {'✅' if x['pred'] == x['expected'] else '❌'} | {x['conf']} | {x['ms']:.0f} |"
         for x in results] + [
        "",
        "## STT word error rate (when you add recorded audio)",
        "Record each demo question as WAV into `eval/audio/<id>.wav`, transcribe with the live STT provider, then:",
        "```python",
        "import jiwer  # pip install jiwer",
        "wer = jiwer.wer(reference_texts, hypothesis_texts)",
        "```",
        "For Telugu/Hindi also report character error rate (`jiwer.cer`), which is fairer for agglutinative words.",
    ]
    out_path = ROOT / "docs" / "EVAL.md"
    out_path.parent.mkdir(exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"hit@1={hit1:.2%} handoff P={prec:.2%} R={rec:.2%} p50={statistics.median(lat):.0f}ms p95={pct(lat, 95):.0f}ms -> {out_path}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["mock", "real"], default="mock")
    asyncio.run(main(ap.parse_args().mode))
